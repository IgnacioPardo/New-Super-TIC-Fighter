// Full application settings, input focus, audio loading, and backend-failure flow.
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {chromium} from '@playwright/test';
const base=process.env.STF_APP_URL??'http://127.0.0.1:5173';
await mkdir('tmp/qa',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1366,height:768}});
const errors=[],music=new Set();
page.on('pageerror',error=>errors.push(error.message));
page.on('request',request=>{if(/\.(mp3|wma)(\?|$)/i.test(request.url()))music.add(request.url());});
await page.addInitScript(()=>{
 const NativeWorker=window.Worker;
 window.Worker=class extends NativeWorker{constructor(...args){super(...args);this.addEventListener('message',event=>{if(event.data?.type==='snapshot')window.__snapshot=event.data.snapshot;});}};
 window.__pad={id:'Menu QA virtual standard gamepad',index:0,connected:true,mapping:'standard',axes:[0,0,0,0],buttons:Array.from({length:17},()=>({pressed:false,value:0,touched:false}))};
 Object.defineProperty(navigator,'getGamepads',{value:()=>[window.__pad]});
});
try{
 await page.goto(base);
 await page.getByTestId('mode-settings').click();
 await page.locator('.volume-field input').first().focus();await page.keyboard.press('Home');
 await page.locator('.volume-field input').nth(1).focus();await page.keyboard.press('Home');
 await page.locator('.settings-tabs button').nth(2).click();
 await page.locator('.binding-button').first().click();
 await page.keyboard.press('d');
 assert.match(await page.locator('.validation-hint').innerText(),/asignada|asignado|uso|used/i,'Conflicting keyboard binding is rejected');
 await page.keyboard.press('f');
 assert.equal(await page.locator('.binding-button').first().locator('kbd').innerText(),'F');
 await page.getByRole('button',{name:'Restaurar teclados originales'}).click();
 assert.equal(await page.locator('.binding-button').first().locator('kbd').innerText(),'A');
 await page.locator('.settings-tabs button').nth(1).click();
 await page.locator('.settings-panel select').nth(0).selectOption('en');
 await page.locator('.settings-panel select').nth(1).selectOption('fixed');
 await page.locator('.toggle-field input[type=checkbox]').check();
 await page.reload();
 await page.getByTestId('mode-settings').click();
 assert.equal(await page.locator('.volume-field input').first().inputValue(),'0');
 assert.equal(await page.locator('.volume-field input').nth(1).inputValue(),'0');
 await page.locator('.settings-tabs button').nth(1).click();
 assert.equal(await page.locator('.settings-panel select').nth(1).inputValue(),'fixed');
 assert.equal(await page.locator('.toggle-field input[type=checkbox]').isChecked(),true);
 await page.locator('.settings-panel select').nth(0).selectOption('es');
 await page.locator('.back-button').click();
 await page.getByTestId('mode-online').click();
 const nickname=page.getByPlaceholder('Jugador',{exact:true});await nickname.fill('Menu QA');await nickname.focus();
 await page.evaluate(()=>window.__pad.buttons[13].pressed=true);await page.waitForTimeout(100);await page.evaluate(()=>window.__pad.buttons[13].pressed=false);
 assert.equal(await nickname.evaluate(element=>document.activeElement===element),false,'Gamepad navigation escapes a focused text field');
 await page.route('**/api/**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'room_service_unavailable'})}));
 await page.getByRole('button',{name:/CREAR SALA/}).click();
 await page.locator('.inline-error').waitFor();
 await page.locator('.back-button').click();
 await page.getByTestId('mode-practice').click();
 await page.locator('.fight-button').click();await page.waitForFunction(()=>window.__snapshot?.phase==='playing');
 assert.equal(await page.locator('canvas').count(),1);
 assert.equal(await page.locator('.global-error').count(),0,'Backend failure does not prevent local practice');
 assert(music.size<=3,`Music must load on demand, not the whole archive (${music.size} tracks requested)`);
 assert.deepEqual(errors,[]);
 await page.screenshot({path:'tmp/qa/menu-practice.png',fullPage:true});
 console.log('Settings persistence, keyboard remapping/conflicts, gamepad text focus, lazy music, and practice with backend unavailable passed.');
}catch(error){console.log((await page.locator('body').innerText()).slice(-3500));await page.screenshot({path:'tmp/qa/menu-failure.png',fullPage:true});throw error;}
finally{await browser.close();}
